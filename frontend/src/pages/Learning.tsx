import { useEffect, useState } from "react";
import { api } from "../api";
import type { Question, Topic, VivaItem } from "../types";
import { Card, ErrorBanner, btn, btnGhost } from "../components/ui";

type Sub = "tutorials" | "quiz" | "viva" | "modules";

export default function Learning() {
  const [sub, setSub] = useState<Sub>("tutorials");
  const [topics, setTopics] = useState<Topic[]>([]);
  const [viva, setViva] = useState<VivaItem[]>([]);
  const [modules, setModules] = useState<{ name: string; explanation: string }[]>([]);
  const [err, setErr] = useState<string | null>(null);
  const [level, setLevel] = useState("beginner");
  const [qs, setQs] = useState<Question[]>([]);
  const [picked, setPicked] = useState<Record<number, number>>({});
  const [open, setOpen] = useState<Record<number, boolean>>({});

  useEffect(() => { api.topics().then((d) => { setTopics(d.topics); setViva(d.viva); setModules(d.modules); }).catch((e: Error) => setErr(e.message)); }, []);
  const newQuiz = async () => { setPicked({}); try { setQs((await api.quiz(level, 5)).questions); } catch (e) { setErr((e as Error).message); } };
  const score = qs.filter((q, i) => picked[i] === q.answer_index).length;

  return (
    <div>
      <ErrorBanner message={err} onClose={() => setErr(null)} />
      <div className="mb-4 flex gap-2">
        {(["tutorials", "quiz", "viva", "modules"] as Sub[]).map((s) => (
          <button key={s} className={sub === s ? btn : btnGhost} onClick={() => setSub(s)}>{s}</button>
        ))}
      </div>
      {sub === "tutorials" && <div className="grid gap-4 md:grid-cols-2">{topics.map((t) => (
        <Card key={t.id} title={t.title}><pre className="whitespace-pre-wrap text-xs text-slate-300">{t.content}</pre></Card>))}</div>}
      {sub === "quiz" && (
        <Card title="Interactive quiz (generated by the Training Bot)">
          <div className="mb-3 flex gap-2">
            <select value={level} onChange={(e) => setLevel(e.target.value)} className="rounded-lg border border-slate-700 bg-slate-950 px-3 py-2 text-sm">
              <option>beginner</option><option>intermediate</option><option>advanced</option>
            </select>
            <button className={btn} onClick={() => void newQuiz()}>Generate quiz</button>
            {qs.length > 0 && <span className="self-center text-sm text-slate-400">Score: {score}/{qs.length}</span>}
          </div>
          {qs.map((q, i) => (
            <div key={i} className="mb-4 rounded-lg border border-slate-800 p-3">
              <div className="mb-2 text-sm font-semibold">{i + 1}. {q.question}</div>
              {q.options.map((o, j) => {
                const chosen = picked[i] !== undefined;
                const style = !chosen ? "border-slate-700 hover:bg-slate-800" : j === q.answer_index ? "border-emerald-600 bg-emerald-950" : picked[i] === j ? "border-rose-600 bg-rose-950" : "border-slate-800 opacity-60";
                return <button key={j} disabled={chosen} onClick={() => setPicked({ ...picked, [i]: j })} className={`mb-1 block w-full rounded border px-3 py-1.5 text-left text-sm ${style}`}>{o}</button>;
              })}
              {picked[i] !== undefined && <p className="mt-2 text-xs text-slate-400">{q.explanation}</p>}
            </div>
          ))}
        </Card>
      )}
      {sub === "viva" && (
        <div className="space-y-3">{viva.map((v, i) => (
          <Card key={i} title={`${v.level} viva question`}>
            <div className="text-sm font-semibold">{v.q}</div>
            <button className={`${btnGhost} mt-2`} onClick={() => setOpen({ ...open, [i]: !open[i] })}>{open[i] ? "hide answer" : "show model answer"}</button>
            {open[i] && <p className="mt-2 text-sm text-slate-300">{v.a}</p>}
          </Card>))}</div>
      )}
      {sub === "modules" && <div className="grid gap-4 md:grid-cols-2">{modules.map((m) => (
        <Card key={m.name} title={m.name}><pre className="max-h-72 overflow-auto whitespace-pre-wrap text-xs text-slate-300">{m.explanation}</pre></Card>))}</div>}
    </div>
  );
}
